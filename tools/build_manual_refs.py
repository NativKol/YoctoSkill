#!/usr/bin/env python3
"""Build per-keyword manual references and per-skill keyword glossaries.

Input: the converted manuals in skills/yocto-manuals/references/manuals/
(produced by tools/convert_manuals.py from the official singleindex pages).

Output:
  skills/yocto-manuals/references/variables/<NAME>.md   Yocto + BitBake glossary entries
  skills/yocto-manuals/references/classes/<name>.md     ref-manual "Classes" sections
  skills/yocto-manuals/references/tasks/<do_task>.md    ref-manual "Tasks" sections
  skills/yocto-manuals/references/features/<kind>/<name>.md  machine/distro/image features
  skills/yocto-manuals/references/qa/<check>.md         QA error and warning messages
  skills/yocto-manuals/references/INDEX.md              one line per keyword
  skills/<skill>/references/keywords.md                 for every skill with keywords.txt

keywords.txt format: one keyword per line, "<kind> <name>", where kind is
var | class | task | qa | feature (feature names are "<distro|machine|image>:<name>").
Lines starting with "#" are comments.

Usage:
    python tools/build_manual_refs.py           # regenerate
    python tools/build_manual_refs.py --check   # fail if outputs are stale or keywords unknown
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MANUAL_SKILL = REPO / "skills" / "yocto-manuals"
REFS = MANUAL_SKILL / "references"
MAN = REFS / "manuals"
YP = "https://docs.yoctoproject.org/scarthgap"
BB = "https://docs.yoctoproject.org/bitbake/2.8"
RELEASE = "Yocto Project 5.0 (scarthgap) / BitBake 2.8"
ATTRIB = (
    "\n---\nRelease: " + RELEASE + ". Text from the Yocto Project documentation, "
    "CC BY-SA 2.0 UK (BitBake manual: CC BY 2.5); converted to Markdown, see "
    "skills/yocto-manuals/LICENSE-docs.md.\n"
)
GEN = "<!-- Generated by tools/build_manual_refs.py. Do not edit; edit the generator. -->\n\n"

ENTRY = re.compile(r"^\*\*([A-Za-z0-9_:\-\[\]]+)\*\*$")


def strip_header(text: str) -> str:
    return re.sub(r"^<!--.*?-->\n+", "", text, flags=re.S)


def split_glossary(path: Path) -> dict[str, str]:
    lines = strip_header(path.read_text(encoding="utf-8")).splitlines()
    out: dict[str, list[str]] = {}
    cur = None
    for line in lines:
        m = ENTRY.match(line)
        if m:
            cur = m.group(1)
            out[cur] = []
            continue
        if cur:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def split_sections(path: Path, pattern: str) -> dict[str, str]:
    """Split on headings matching pattern; group(1) is the name; stop at same-or-higher level."""
    lines = strip_header(path.read_text(encoding="utf-8")).splitlines()
    rx = re.compile(pattern)
    out: dict[str, list[str]] = {}
    cur = None
    level = 0
    for line in lines:
        m = rx.match(line)
        h = re.match(r"^(#+) ", line)
        if m:
            cur = m.group(1)
            level = len(h.group(1)) if h else 0
            out[cur] = []
            continue
        if cur and h and len(h.group(1)) <= level:
            cur = None
        if cur:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def bullet_items(body: str) -> dict[str, str]:
    """Feature lists look like '- *name:* text' followed by continuation paragraphs."""
    out: dict[str, list[str]] = {}
    cur = None
    for line in body.splitlines():
        m = re.match(r"^- \*([A-Za-z0-9_.+\-]+):\*\s*(.*)$", line)
        if m:
            cur = m.group(1)
            out[cur] = [m.group(2)]
            continue
        if cur and line.startswith("- "):
            cur = None
        if cur:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def qa_items(body: str) -> dict[str, str]:
    out: dict[str, list[str]] = {}
    cur = None
    for line in body.splitlines():
        m = re.match(r"^- `(.*)\[([a-z0-9\-]+)\]`\s*$", line)
        if m:
            cur = m.group(2)
            out.setdefault(cur, []).append("Message: `" + m.group(1).strip() + " [" + cur + "]`\n")
            continue
        if line.startswith("- ") or line.startswith("#"):
            cur = None
        if cur:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.\-]", "_", name).strip("_")


def collect() -> dict[tuple[str, str], tuple[str, str]]:
    """Return {(kind, name): (markdown body, source url)}."""
    kw: dict[tuple[str, str], tuple[str, str]] = {}
    yv = split_glossary(MAN / "ref-manual" / "variables.md")
    bv = split_glossary(MAN / "bitbake-user-manual" / "bitbake-user-manual-ref-variables.md")
    for name in sorted(set(yv) | set(bv)):
        parts, urls = [], []
        if name in yv:
            parts.append("## Yocto Project Reference Manual\n\n" + yv[name])
            urls.append(f"{YP}/ref-manual/variables.html#term-{name}")
        if name in bv:
            parts.append("## BitBake User Manual\n\n" + bv[name])
            urls.append(f"{BB}/bitbake-user-manual/bitbake-user-manual-ref-variables.html#term-{name}")
        kw[("var", name)] = ("\n\n".join(parts), " , ".join(urls))
    cls = split_sections(MAN / "ref-manual" / "classes.md", r"^##### 5\.\d+ `([^`]+)`$")
    for name, body in cls.items():
        n = name.rstrip("*_")
        kw[("class", n)] = (body, f"{YP}/ref-manual/classes.html#ref-classes-{safe(n)}")
    tsk = split_sections(MAN / "ref-manual" / "tasks.md", r"^###### 6\.\d+\.\d+ `([^`]+)`$")
    for name, body in tsk.items():
        kw[("task", name)] = (body, f"{YP}/ref-manual/tasks.html#{name.replace('_', '-')}")
    feat = split_sections(MAN / "ref-manual" / "features.md", r"^##### 11\.\d+ (Machine|Distro|Image) Features$")
    for kind, body in feat.items():
        for name, text in bullet_items(body).items():
            k = kind.lower()
            kw[("feature", f"{k}:{name}")] = (
                f"{kind} feature `{name}`:\n\n{text}",
                f"{YP}/ref-manual/features.html#{k}-features",
            )
    qa_body = (MAN / "ref-manual" / "qa-checks.md").read_text(encoding="utf-8")
    for name, body in qa_items(qa_body).items():
        kw[("qa", name)] = (body, f"{YP}/ref-manual/qa-checks.html")
    return kw


def path_for(kind: str, name: str) -> Path:
    if kind == "var":
        return REFS / "variables" / f"{safe(name)}.md"
    if kind == "class":
        return REFS / "classes" / f"{safe(name)}.md"
    if kind == "task":
        return REFS / "tasks" / f"{safe(name)}.md"
    if kind == "qa":
        return REFS / "qa" / f"{safe(name)}.md"
    fk, fn = name.split(":", 1)
    return REFS / "features" / fk / f"{safe(fn)}.md"


TITLE = {"var": "Variable", "class": "Class", "task": "Task", "qa": "QA check", "feature": "Feature"}


def render_entry(kind: str, name: str, body: str, url: str, level: str = "#") -> str:
    return f"{level} {TITLE[kind]} `{name}`\n\n{body.strip()}\n\nSource: {url}\n"


def first_sentence(body: str) -> str:
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and not line.startswith("```"):
            s = re.split(r"(?<=[.!?])\s", line, maxsplit=1)[0]
            return s[:160]
    return ""


def build(check: bool) -> int:
    kw = collect()
    want: dict[Path, str] = {}
    for (kind, name), (body, url) in kw.items():
        want[path_for(kind, name)] = GEN + render_entry(kind, name, body, url) + ATTRIB
    idx = [GEN + "# Keyword index — " + RELEASE + "\n",
           "Find a keyword here, then read the file named in the last column (relative to this folder).\n",
           "Grep tip: `grep -i '^| var | IMAGE_' INDEX.md`.\n",
           "| kind | name | summary | file |", "|---|---|---|---|"]
    for (kind, name) in sorted(kw, key=lambda k: (k[0], k[1].lower())):
        body, _ = kw[(kind, name)]
        rel = path_for(kind, name).relative_to(REFS).as_posix()
        summ = first_sentence(body).replace("|", "\\|")
        idx.append(f"| {kind} | {name} | {summ} | {rel} |")
    want[REFS / "INDEX.md"] = "\n".join(idx) + "\n"

    # Table of contents of the full manuals: every document with its section headings.
    toc_lines = [GEN + "# Manuals table of contents — " + RELEASE + "\n",
                 "Every converted manual page under `manuals/`, with its section headings. "
                 "Grep this file for a topic, then read the named file (paths relative to this folder).\n"]
    for doc in sorted(MAN.rglob("*.md")):
        rel = doc.relative_to(REFS).as_posix()
        heads, fence = [], False
        for l in strip_header(doc.read_text(encoding="utf-8")).splitlines():
            if l.startswith("```"):
                fence = not fence
            elif not fence and re.match(r"^#{1,6} ", l):
                heads.append(l)
        if not heads:
            continue
        toc_lines.append(f"\n## {rel}\n")
        base = min(len(h.split(" ", 1)[0]) for h in heads)
        for h in heads[:80]:
            marks, text = h.split(" ", 1)
            depth = len(marks) - base
            if depth <= 2:
                toc_lines.append("  " * depth + "- " + text.strip())
    want[REFS / "MANUALS.md"] = "\n".join(toc_lines) + "\n"

    errors = []
    for kwfile in sorted((REPO / "skills").glob("*/keywords.txt")):
        skill = kwfile.parent.name
        parts = [GEN + f"# Keyword glossary for `{skill}` — {RELEASE}\n",
                 "Verbatim entries from the official manuals for every keyword this skill relies on. "
                 "Text: Yocto Project documentation, CC BY-SA 2.0 UK (BitBake manual: CC BY 2.5).\n"]
        toc = []
        entries = []
        for raw in kwfile.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            kind, _, name = line.partition(" ")
            name = name.strip()
            if (kind, name) not in kw:
                errors.append(f"{kwfile.relative_to(REPO)}: unknown keyword '{line}'")
                continue
            body, url = kw[(kind, name)]
            toc.append(f"- {TITLE[kind]} `{name}`")
            entries.append(render_entry(kind, name, body, url, level="##"))
        parts.append("## Contents\n\n" + "\n".join(toc) + "\n")
        parts.extend(entries)
        want[kwfile.parent / "references" / "keywords.md"] = "\n".join(parts)

    # Remove stale generated per-keyword files.
    stale = []
    for sub in ("variables", "classes", "tasks", "qa", "features"):
        for p in (REFS / sub).rglob("*.md") if (REFS / sub).exists() else []:
            if p not in want:
                stale.append(p)

    changed = [p for p, t in want.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if check:
        for p in changed:
            errors.append(f"out of date: {p.relative_to(REPO)}")
        for p in stale:
            errors.append(f"stale: {p.relative_to(REPO)}")
    else:
        for p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(want[p], encoding="utf-8")
        for p in stale:
            p.unlink()
        counts = {}
        for kind, _ in kw:
            counts[kind] = counts.get(kind, 0) + 1
        print("keywords:", ", ".join(f"{k}={v}" for k, v in sorted(counts.items())),
              f"| wrote {len(changed)} files, removed {len(stale)}")
    for e in errors:
        print("ERROR:", e, file=sys.stderr)
    return 1 if errors else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    return build(ap.parse_args().check)


if __name__ == "__main__":
    sys.exit(main())
